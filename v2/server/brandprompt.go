func directionsFor(f BrandForm) []Direction {
	hay := f["industry"] + " " + f["products"] + " " + f["keywords"] + " " + f["positioning"]
	for _, set := range directionSets {
		for _, k := range set.keys {
			if strings.Contains(hay, k) {
				return set.dirs[:]
			}
		}
	}
	return defaultDirections[:]
}

func DirectionPrompts(f BrandForm) []string {
	out := make([]string, 3)
	for i, d := range directionsFor(f) {
		out[i] = fmt.Sprintf("【唯一方向】%s\n\n%s", d.Name, directionPrompt(f, d))
	}
	return out
}

