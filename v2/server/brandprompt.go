func normalizeForm(raw BrandForm) BrandForm {
	f := BrandForm{}
	for k, v := range raw {
		v = strings.TrimSpace(v)
		if v != "" {
			f[k] = v
		}
	}
	hintC, hintS, hintP := "中性纸色/炭黑/金属", "按品牌行业与关键词决定，不预设单一风格", "自然光、材质细节"
	hay := f["industry"] + " " + f["products"] + " " + f["keywords"]
	for _, h := range industryHints {
		for _, k := range h.keys {
			if strings.Contains(hay, k) {
				hintC, hintS, hintP = h.colors, h.style, h.photo
				break
			}
		}
		if hintS != "按品牌行业与关键词决定，不预设单一风格" {
			break
		}
	}
	setDefault := func(k, v string) {
		if _, ok := f[k]; !ok {
			f[k] = v
		}
	}
	if _, ok := f["industry"]; !ok {
		f["industry"] = "生活方式"
	}
	setDefault("style", hintS)
	parts := strings.Split(hintC, "/")
	setDefault("primary_color", parts[0])
	if len(parts) > 1 {
		setDefault("accent_colors", strings.Join(parts[1:], "/"))
	} else {
		setDefault("accent_colors", "炭黑")
	}
	setDefault("materials", hintC)
	setDefault("photography", hintP)
	setDefault("scenarios", "主产品、礼盒、手提袋、卡片、标牌")
	setDefault("ratio", "4:5 竖版（1024×1280）")
	setDefault("lang", "中英结合")
	setDefault("logo_type", "抽象符号")
	if _, ok := f["slogan"]; !ok {
		if p, ok2 := f["philosophy"]; ok2 && p != "" {
			f["slogan"] = truncate(p, 12)
		}
	}
	setDefault("avoid", "无")
	setDefault("extra", "无")
	setDefault("en_name", "")
	return f
}

func truncate(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n])
}

