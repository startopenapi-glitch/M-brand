const fixedRule = "每张图固定要素：醒目大主标题（参与构图，可放大/裁切/错位/纵向/与图片穿插）；一个短副标题；一句核心说明；2-4 个关键词标签；2-4 处简短清晰的手写注释；恰一个视觉中心；留白 25%-35%。"

func BoardPrompts(f BrandForm) []boardSpec {
	specs := boardSpecs(f)
	byN := map[int]boardSpec{}
	for _, s := range specs {
		byN[s.N] = s
	}
	out := make([]boardSpec, 0, 4)
	for _, n := range []int{2, 1, 3, 4} {
		s := byN[n]
		s.Body = fmt.Sprintf("%s\n\n%s\n\n%s\n\n输出 4:5 竖版独立成图，%s。",
			fmt.Sprintf("%s\n\n%s\n\n【任务】图 %d｜%s\n%s", commonRule, ctxOf(f), s.N, s.Title, s.Body),
			s.Rule, fixedRule, f["lang"])
		out = append(out, s)
	}
	return out
}
